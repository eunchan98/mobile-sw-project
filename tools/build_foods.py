def is_usable(row):
    if row["업체명"] not in ("해당없음", ""):
        return False
    if "간편조리세트" in row["식품명"]:
        return False
    return all(row[n].strip() for n in NUTRIENTS)


def pick(rows):
    adult = [r for r in rows if r["식품기원명"] in ADULT_SOURCES]
    chosen = adult or rows
    values = [statistics.median(float(r[n]) for r in chosen) for n in NUTRIENTS]
    return values, ("성인" if adult else "기타"), len(chosen)


def main(src: str, out: str) -> None:
    with open(src, encoding="cp949", newline="") as f:
        rows = [r for r in csv.DictReader(f) if is_usable(r)]
    by_name = {}
    for r in rows:
        by_name.setdefault(r["식품명"], []).append(r)

    names = [m[2] for m in MENU]
    assert len(set(names)) == len(names), "표시 이름이 겹칩니다"

    base_date = rows[0]["데이터기준일자"]
    lines = [
        "# 출처: 식품의약품안전처 전국통합식품영양성분정보(음식)표준데이터",
        f"# 데이터 기준일자: {base_date}",
        "# 값: 100g 기준(음료는 100ml). 업체 제품 제외, 성인 대상 출처(산업체급식·가정식·외식) 중간값",
        "# tools/build_foods.py로 생성한 파일이므로 직접 고치지 말고 스크립트를 수정한다.",
        "id,name,category,kcal,carbs,protein,fat",
    ]
    missing, fallback = [], []
    for i, (category, src_name, name) in enumerate(MENU, start=1):
        if src_name not in by_name:
            missing.append(src_name)
            continue
        (kcal, carbs, protein, fat), origin, n = pick(by_name[src_name])
        if origin != "성인":
            fallback.append(name)
        lines.append(f"{i},{name},{category},{kcal:g},{carbs:.1f},{protein:.1f},{fat:.1f}")
        print(f"{i:3} {name:<12} {origin} {n}건  {kcal:g}kcal 탄{carbs:.1f} 단{protein:.1f} 지{fat:.1f}")

    if missing:
        sys.exit(f"원본에 없는 식품명: {missing}")
    Path(out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\n{len(MENU)}종 저장: {out}")
    if fallback:
        print(f"성인 출처가 없어 다른 출처 값을 쓴 음식: {fallback}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    repo = Path(__file__).resolve().parent.parent
    main(sys.argv[1], str(repo / "app/src/main/assets/foods.csv"))
